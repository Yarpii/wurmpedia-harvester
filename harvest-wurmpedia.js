class WurmpediaHarvester {
  constructor() {
    this.api = new WurmpediaAPI();
    this.db = new SimpleDB(CONFIG.DATA_DIR);
    this.checkpoint = new Checkpoint(CONFIG.CHECKPOINT_FILE);
    this.extractor = new RecipeExtractor();
  }
  
  // Phase 1: Fetch all page metadata
  async harvestPages() {
    console.log("\n📡 Phase 1: Fetching all pages...\n");
    
    if (this.checkpoint.isPhaseComplete("pages")) {
      console.log("  ✅ Pages already harvested, skipping...");
      return;
    }
    
    this.checkpoint.startPhase("pages");
    
    let count = 0;
    const batchSize = 100;
    let batch = [];
    
    for await (const page of this.api.getAllPages()) {
      batch.push(page);
      count++;
      
      if (batch.length >= batchSize) {
        // Fetch categories for batch
        const pageIds = batch.map(p => p.pageid);
        const categories = await this.api.getCategories(pageIds);
        
        // Save pages
        for (const p of batch) {
          this.db.addPage(p.pageid, p.title, p.ns, categories[p.pageid] || []);
        }
        
        this.db.saveBatch();
        this.checkpoint.updateProgress("pages", "count", count);
        
        console.log(`  📦 Processed ${count} pages...`);
        batch = [];
      }
    }
    
    // Process remaining batch
    if (batch.length > 0) {
      const pageIds = batch.map(p => p.pageid);
      const categories = await this.api.getCategories(pageIds);
      
      for (const p of batch) {
        this.db.addPage(p.pageid, p.title, p.ns, categories[p.pageid] || []);
      }
      
      this.db.saveBatch();
    }
    
    this.checkpoint.completePhase("pages");
    console.log(`\n  ✅ Harvested ${count} pages total\n`);
  }
  
  // Phase 2: Fetch page content
  async harvestContent() {
    console.log("\n📄 Phase 2: Fetching page content...\n");
    
    if (this.checkpoint.isPhaseComplete("content")) {
      console.log("  ✅ Content already harvested, skipping...");
      return;
    }
    
    this.checkpoint.startPhase("content");
    
    const pageIds = this.db.getPagesWithoutContent();
    const total = pageIds.length;
    
    console.log(`  📊 Pages to fetch: ${total}\n`);
    
    if (total === 0) {
      this.checkpoint.completePhase("content");
      return;
    }
    
    const progress = new ProgressTracker(total, "  Fetching");
    let processed = 0;
    let errors = 0;
    
    // Process in batches
    for (let i = 0; i < pageIds.length; i += CONFIG.BATCH_SIZE) {
      const batch = pageIds.slice(i, i + CONFIG.BATCH_SIZE);
      
      try {
        const contents = await this.api.getPageContents(batch);
        
        for (const [pageId, content] of Object.entries(contents)) {
          this.db.saveContent(Number(pageId), content);
        }
        
        processed += batch.length;
        progress.update(processed);
        
        // Save checkpoint periodically
        if (processed % 200 === 0) {
          this.db.saveBatch();
          this.checkpoint.updateProgress("content", "processed", processed);
        }
      } catch (error) {
        console.error(`\n  ⚠️ Batch error: ${error.message}`);
        errors++;
        
        // Try individual fetches for failed batch
        for (const pageId of batch) {
          try {
            const content = await this.api.getPageContent(pageId);
            if (content) {
              this.db.saveContent(pageId, content);
            }
            processed++;
            progress.update(processed);
          } catch (e) {
            console.error(`\n  ❌ Failed: ${pageId}`);
            errors++;
          }
        }
      }
    }
    
    progress.done();
    this.db.saveBatch();
    this.checkpoint.completePhase("content");
    
    console.log(`\n  ✅ Fetched ${processed} pages (${errors} errors)\n`);
  }
  
  // Phase 3: Extract recipes
  async extractRecipes() {
    console.log("\n🍳 Phase 3: Extracting recipes...\n");
    
    if (this.checkpoint.isPhaseComplete("recipes")) {
      console.log("  ✅ Recipes already extracted, skipping...");
      return;
    }
    
    this.checkpoint.startPhase("recipes");
    
    const pageIds = this.db.getAllPageIds();
    const progress = new ProgressTracker(pageIds.length, "  Extracting");
    
    let extracted = 0;
    let checked = 0;
    
    for (const pageId of pageIds) {
      const content = this.db.getContent(pageId);
      
      if (content) {
        const recipe = this.extractor.extract(content);
        
        if (recipe) {
          this.db.saveRecipe(pageId, recipe);
          extracted++;
        }
      }
      
      checked++;
      progress.update(checked);
      
      // Save periodically
      if (checked % 500 === 0) {
        this.db.saveBatch();
        this.checkpoint.updateProgress("recipes", "extracted", extracted);
      }
    }
    
    progress.done();
    this.db.saveBatch();
    this.checkpoint.completePhase("recipes");
    
    console.log(`\n  ✅ Extracted ${extracted} recipes from ${checked} pages\n`);
  }
  
  // Full harvest
  async harvest() {
    console.log("🔨 Wurmpedia Complete Harvester v2.0");
    console.log("=====================================\n");
    
    const startTime = Date.now();
    
    await this.harvestPages();
    await this.harvestContent();
    await this.extractRecipes();
    
    const elapsed = (Date.now() - startTime) / 1000;
    
    console.log("\n=====================================");
    console.log("✅ Harvest complete!\n");
    
    this.showStats();
    
    console.log(`\n⏱️  Total time: ${(elapsed / 60).toFixed(1)} minutes`);
  }
  
  // Resume interrupted harvest
  async resume() {
    console.log("🔄 Resuming harvest...\n");
    
    if (!this.checkpoint.isPhaseComplete("pages")) {
      await this.harvestPages();
    }
    
    if (!this.checkpoint.isPhaseComplete("content")) {
      await this.harvestContent();
    }
    
    if (!this.checkpoint.isPhaseComplete("recipes")) {
      await this.extractRecipes();
    }
    
    console.log("\n✅ Resume complete!");
    this.showStats();
  }
  
  // Show statistics
  showStats() {
    console.log("📊 Database Statistics:");
    console.log(`   Total pages: ${this.db.index.stats.total}`);
    console.log(`   With content: ${this.db.index.stats.withContent}`);
    console.log(`   With recipes: ${this.db.index.stats.withRecipes}`);
    
    // Category counts
    const cats = Object.entries(this.db.index.byCategory)
      .sort((a, b) => b[1].length - a[1].length)
      .slice(0, 15);
    
    console.log("\n🏷️  Top categories:");
    for (const [cat, pages] of cats) {
      console.log(`   ${cat}: ${pages.length} pages`);
    }
    
    // Recipe types
    const recipes = this.db.getAllRecipes();
    const byType = {};
    for (const recipe of recipes) {
      byType[recipe.type] = (byType[recipe.type] || 0) + 1;
    }
    
    console.log("\n🍳 Recipe types:");
    for (const [type, count] of Object.entries(byType).sort((a, b) => b[1] - a[1])) {
      console.log(`   ${type}: ${count} recipes`);
    }
  }
  
  // Export to JSON files
  async export() {
    console.log("\n📦 Exporting to JSON files...\n");
    
    const exportDir = path.join(CONFIG.DATA_DIR, "export");
    if (!fs.existsSync(exportDir)) {
      fs.mkdirSync(exportDir, { recursive: true });
    }
    
    // Export page index
    const pagesFile = path.join(exportDir, "pages.json");
    const pages = Object.entries(this.db.index.pages).map(([id, p]) => ({
      pageid: Number(id),
      ...p
    }));
    fs.writeFileSync(pagesFile, JSON.stringify(pages, null, 2));
    console.log(`  ✅ Exported ${pages.length} pages to pages.json`);
    
    // Export all recipes
    const recipesFile = path.join(exportDir, "recipes.json");
    const recipes = this.db.getAllRecipes();
    fs.writeFileSync(recipesFile, JSON.stringify(recipes, null, 2));
    console.log(`  ✅ Exported ${recipes.length} recipes to recipes.json`);
    
    // Export cooking recipes
    const cookingFile = path.join(exportDir, "cooking-recipes.json");
    const cooking = recipes.filter(r => r.type === "cooking");
    fs.writeFileSync(cookingFile, JSON.stringify(cooking, null, 2));
    console.log(`  ✅ Exported ${cooking.length} cooking recipes`);
    
    // Export crafting recipes
    const craftingFile = path.join(exportDir, "crafting-recipes.json");
    const crafting = recipes.filter(r => r.type === "crafting");
    fs.writeFileSync(craftingFile, JSON.stringify(crafting, null, 2));
    console.log(`  ✅ Exported ${crafting.length} crafting recipes`);
    
    // Export categories index
    const categoriesFile = path.join(exportDir, "categories.json");
    fs.writeFileSync(categoriesFile, JSON.stringify(this.db.index.byCategory, null, 2));
    console.log(`  ✅ Exported ${Object.keys(this.db.index.byCategory).length} categories`);
    
    // High-confidence recipes only
    const highConfFile = path.join(exportDir, "recipes-high-confidence.json");
    const highConf = recipes.filter(r => r.confidence >= 0.5);
    fs.writeFileSync(highConfFile, JSON.stringify(highConf, null, 2));
    console.log(`  ✅ Exported ${highConf.length} high-confidence recipes`);
    
    console.log(`\n  📁 Files saved to: ${exportDir}`);
  }
}

