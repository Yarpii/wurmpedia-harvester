class RecipeExtractor {
  constructor() {
    // Patterns for finding recipe-like content
    this.patterns = {
      // Skill requirement patterns
      skill: /(?:skill|requires?)\s*(?::|=)?\s*([A-Za-z\s]+?)(?:\s*\d+|\s*$|\s*\n)/gi,
      
      // Ingredients/materials
      ingredients: /(?:ingredients?|materials?|requires?|needs?)\s*(?::|=)?\s*\n?([\s\S]*?)(?=\n\n|\n(?:[A-Z]|\*\s*[A-Z])|\Z)/gi,
      
      // Tool requirements
      tools: /(?:tools?|using|with|active(?:\s+item)?)\s*(?::|=)?\s*([^\n]+)/gi,
      
      // Container requirements
      container: /(?:container|in\s+a?)\s*(?::|=)?\s*([^\n,]+)/gi,
      
      // Output/creates
      output: /(?:creates?|produces?|output|makes?|results?\s+in)\s*(?::|=)?\s*([^\n]+)/gi,
      
      // Quality level
      quality: /(?:ql|quality)\s*(?::|=)?\s*(\d+)/gi,
      
      // Table rows (common wiki format)
      tableRow: /\|-\s*\n\|([^|]+)\|([^|]+)/g,
      
      // Wiki template parameters
      templateParam: /\|\s*(\w+)\s*=\s*([^|}\n]+)/g
    };
    
    // Cooking-specific patterns
    this.cookingPatterns = {
      cooker: /(?:cooker|oven|forge|campfire|fire)\s*(?::|=|,)?\s*([^\n,|]+)?/gi,
      cookingContainer: /(?:pottery\s*bowl|frying\s*pan|sauce\s*pan|cauldron|baking\s*stone|cake\s*tin|roasting\s*dish|pie\s*dish)/gi,
      mandatory: /mandatory\s*(?::|=)?\s*([^\n]+)/gi,
      optional: /optional\s*(?::|=)?\s*([^\n]+)/gi
    };
    
    // Common Wurm items for validation
    this.knownItems = new Set([
      "iron", "steel", "copper", "gold", "silver", "zinc", "tin", "lead",
      "wood", "log", "plank", "shaft", "handle", "blade",
      "stone", "rock", "clay", "sand", "dirt",
      "water", "salt", "flour", "dough", "meat", "fish", "vegetable",
      "leather", "cloth", "wool", "string", "rope",
      "nail", "rivet", "lump", "bar", "sheet"
    ]);
    
    // Recipe categories to look for
    this.recipeCategories = [
      "Recipes", "Cooking", "Crafting", "Blacksmithing", "Carpentry",
      "Masonry", "Tailoring", "Leatherworking", "Pottery", "Jewelry",
      "Alchemy", "Beverages", "Baking", "Hot food cooking", "Food"
    ];
  }
  
  hasRecipeContent(pageData) {
    const text = (pageData.wikitext || pageData.html || "").toLowerCase();
    const title = (pageData.title || "").toLowerCase();
    const categories = pageData.categories || [];
    
    // Check categories first
    for (const cat of categories) {
      if (this.recipeCategories.some(rc => cat.toLowerCase().includes(rc.toLowerCase()))) {
        return true;
      }
    }
    
    // Check for recipe indicators in content
    let indicatorCount = 0;
    for (const indicator of CONFIG.RECIPE_INDICATORS) {
      if (text.includes(indicator.toLowerCase())) {
        indicatorCount++;
      }
    }
    
    // Need at least 2 indicators
    return indicatorCount >= 2;
  }
  
  extract(pageData) {
    if (!this.hasRecipeContent(pageData)) {
      return null;
    }
    
    const wikitext = pageData.wikitext || "";
    const html = pageData.html || "";
    const title = pageData.title || "";
    
    const recipe = {
      pageid: pageData.pageid,
      title: title,
      type: this.determineRecipeType(pageData),
      categories: pageData.categories || [],
      extracted: {
        skills: this.extractSkills(wikitext),
        ingredients: this.extractIngredients(wikitext),
        tools: this.extractTools(wikitext),
        containers: this.extractContainers(wikitext),
        output: this.extractOutput(wikitext, title),
        difficulty: this.extractDifficulty(wikitext),
        time: this.extractTime(wikitext)
      },
      cooking: null,
      crafting: null,
      raw: {
        hasTable: wikitext.includes("{|") || html.includes("<table"),
        hasTemplate: wikitext.includes("{{"),
        hasInfobox: wikitext.toLowerCase().includes("infobox")
      },
      confidence: 0
    };
    
    // Extract cooking-specific data
    if (this.isCookingRecipe(pageData)) {
      recipe.cooking = this.extractCookingRecipe(wikitext);
      recipe.type = "cooking";
    }
    
    // Extract crafting-specific data
    if (this.isCraftingRecipe(pageData)) {
      recipe.crafting = this.extractCraftingRecipe(wikitext);
      if (!recipe.cooking) recipe.type = "crafting";
    }
    
    // Calculate confidence score
    recipe.confidence = this.calculateConfidence(recipe);
    
    // Only return if we have meaningful data
    if (recipe.confidence > 0.2) {
      return recipe;
    }
    
    return null;
  }
  
  determineRecipeType(pageData) {
    const cats = (pageData.categories || []).map(c => c.toLowerCase());
    const text = (pageData.wikitext || "").toLowerCase();
    
    if (cats.some(c => c.includes("cooking") || c.includes("food") || c.includes("beverage"))) {
      return "cooking";
    }
    if (cats.some(c => c.includes("weapon") || c.includes("armor") || c.includes("tool"))) {
      return "crafting";
    }
    if (text.includes("cooker") || text.includes("cookbook")) {
      return "cooking";
    }
    if (text.includes("activate") && text.includes("create")) {
      return "crafting";
    }
    
    return "unknown";
  }
  
  isCookingRecipe(pageData) {
    const cats = (pageData.categories || []).map(c => c.toLowerCase());
    const text = (pageData.wikitext || "").toLowerCase();
    
    return cats.some(c => 
      c.includes("cooking") || c.includes("food") || 
      c.includes("beverage") || c.includes("recipe")
    ) || text.includes("cookbook") || text.includes("cooker");
  }
  
  isCraftingRecipe(pageData) {
    const cats = (pageData.categories || []).map(c => c.toLowerCase());
    const text = (pageData.wikitext || "").toLowerCase();
    
    return cats.some(c => 
      c.includes("crafting") || c.includes("item") ||
      c.includes("weapon") || c.includes("armor") || c.includes("tool")
    ) || (text.includes("activate") && text.includes("create"));
  }
  
  extractSkills(text) {
    const skills = new Set();
    const skillPattern = /(?:skill|requires?)\s*(?::|=)?\s*\[\[([^\]]+)\]\]|(?:skill|requires?)\s*(?::|=)?\s*([A-Za-z\s]+?)(?:\s+\d|\s*$)/gi;
    
    let match;
    while ((match = skillPattern.exec(text)) !== null) {
      const skill = (match[1] || match[2] || "").trim();
      if (skill && skill.length > 2 && skill.length < 50) {
        skills.add(skill);
      }
    }
    
    // Also look for known skill names
    const knownSkills = [
      "Blacksmithing", "Carpentry", "Masonry", "Pottery", "Cooking",
      "Hot food cooking", "Baking", "Beverages", "Alchemy", "Tailoring",
      "Leatherworking", "Ropemaking", "Smithing", "Fine carpentry"
    ];
    
    for (const skill of knownSkills) {
      if (text.toLowerCase().includes(skill.toLowerCase())) {
        skills.add(skill);
      }
    }
    
    return Array.from(skills);
  }
  
  extractIngredients(text) {
    const ingredients = [];
    
    // Look for list items
    const listPattern = /^\*\s*(.+)$/gm;
    let match;
    while ((match = listPattern.exec(text)) !== null) {
      const item = match[1].trim()
        .replace(/\[\[([^\]|]+)\|?[^\]]*\]\]/g, "$1")  // Remove wiki links
        .replace(/'''?/g, "")  // Remove bold
        .trim();
      
      if (item && item.length > 1 && item.length < 100) {
        // Parse quantity if present
        const qtyMatch = item.match(/^(\d+(?:\.\d+)?)\s*(?:x|×)?\s*(.+)$/);
        if (qtyMatch) {
          ingredients.push({
            quantity: parseFloat(qtyMatch[1]),
            item: qtyMatch[2].trim()
          });
        } else {
          ingredients.push({ quantity: 1, item: item });
        }
      }
    }
    
    // Also look for table rows
    const tablePattern = /\|\s*(\d+(?:\.\d+)?)\s*\|\s*([^|\n]+)/g;
    while ((match = tablePattern.exec(text)) !== null) {
      const item = match[2].trim()
        .replace(/\[\[([^\]|]+)\|?[^\]]*\]\]/g, "$1")
        .trim();
      
      if (item && item.length > 1) {
        ingredients.push({
          quantity: parseFloat(match[1]),
          item: item
        });
      }
    }
    
    return ingredients;
  }
  
  extractTools(text) {
    const tools = new Set();
    
    // Common tool patterns
    const patterns = [
      /(?:activate|use|with)\s+(?:a\s+)?([a-z\s]+?)(?:\s+on|\s+and|$)/gi,
      /(?:tool|using)\s*(?::|=)?\s*\[\[([^\]]+)\]\]/gi,
      /(?:tool|using)\s*(?::|=)?\s*([A-Za-z\s]+?)(?:\s*$|\s*\n)/gi
    ];
    
    for (const pattern of patterns) {
      let match;
      while ((match = pattern.exec(text)) !== null) {
        const tool = (match[1] || "").trim().toLowerCase();
        if (tool && tool.length > 2 && tool.length < 30) {
          tools.add(tool);
        }
      }
    }
    
    // Known tools
    const knownTools = [
      "hammer", "mallet", "saw", "chisel", "file", "awl", "needle",
      "knife", "carving knife", "butchering knife", "pickaxe", "shovel",
      "rake", "hoe", "sickle", "scythe", "trowel", "spatula",
      "grindstone", "pelt", "whetstone", "spindle", "loom"
    ];
    
    for (const tool of knownTools) {
      if (text.toLowerCase().includes(tool)) {
        tools.add(tool);
      }
    }
    
    return Array.from(tools);
  }
  
  extractContainers(text) {
    const containers = new Set();
    const lower = text.toLowerCase();
    
    const knownContainers = [
      "pottery bowl", "frying pan", "sauce pan", "cauldron",
      "baking stone", "cake tin", "roasting dish", "pie dish",
      "barrel", "small barrel", "large barrel", "bucket",
      "forge", "oven", "campfire"
    ];
    
    for (const container of knownContainers) {
      if (lower.includes(container)) {
        containers.add(container);
      }
    }
    
    return Array.from(containers);
  }
  
  extractOutput(text, title) {
    // Often the page title IS the output
    const outputs = [title];
    
    // Look for explicit output statements
    const pattern = /(?:creates?|produces?|makes?|results?\s+in)\s*(?::|=)?\s*\[\[([^\]]+)\]\]|(?:creates?|produces?|makes?)\s+(\d+)?\s*([a-z\s]+)/gi;
    let match;
    while ((match = pattern.exec(text)) !== null) {
      const output = (match[1] || match[3] || "").trim();
      if (output && output.length > 1 && !outputs.includes(output)) {
        outputs.push(output);
      }
    }
    
    return outputs;
  }
  
  extractDifficulty(text) {
    const patterns = [
      /difficulty\s*(?::|=)?\s*(\d+)/i,
      /diff\s*(?::|=)?\s*(\d+)/i,
      /skill\s+level\s*(?::|=)?\s*(\d+)/i
    ];
    
    for (const pattern of patterns) {
      const match = text.match(pattern);
      if (match) {
        return parseInt(match[1]);
      }
    }
    
    return null;
  }
  
  extractTime(text) {
    const patterns = [
      /(?:time|duration)\s*(?::|=)?\s*(\d+)\s*(seconds?|minutes?|hours?)/i,
      /takes?\s+(\d+)\s*(seconds?|minutes?|hours?)/i
    ];
    
    for (const pattern of patterns) {
      const match = text.match(pattern);
      if (match) {
        const value = parseInt(match[1]);
        const unit = match[2].toLowerCase();
        
        // Normalize to seconds
        if (unit.startsWith("minute")) return value * 60;
        if (unit.startsWith("hour")) return value * 3600;
        return value;
      }
    }
    
    return null;
  }
  
  extractCookingRecipe(text) {
    const cooking = {
      cooker: null,
      container: null,
      mandatory: [],
      optional: [],
      oneOrMore: []
    };
    
    // Extract cooker type
    const cookerMatch = text.match(/(?:cooker|cooked?\s+in)\s*(?::|=)?\s*([^\n,|]+)/i);
    if (cookerMatch) {
      cooking.cooker = cookerMatch[1].trim();
    }
    
    // Extract container
    const containers = ["pottery bowl", "frying pan", "sauce pan", "cauldron", 
                       "baking stone", "cake tin", "roasting dish", "pie dish"];
    for (const container of containers) {
      if (text.toLowerCase().includes(container)) {
        cooking.container = container;
        break;
      }
    }
    
    // Extract mandatory ingredients
    const mandatoryMatch = text.match(/mandatory\s*(?::|=)?\s*([^\n]+)/i);
    if (mandatoryMatch) {
      cooking.mandatory = mandatoryMatch[1]
        .split(/[,;]/)
        .map(s => s.trim())
        .filter(s => s.length > 0);
    }
    
    // Extract optional ingredients
    const optionalMatch = text.match(/optional\s*(?::|=)?\s*([^\n]+)/i);
    if (optionalMatch) {
      cooking.optional = optionalMatch[1]
        .split(/[,;]/)
        .map(s => s.trim())
        .filter(s => s.length > 0);
    }
    
    // Extract "one or more"
    const oneOrMoreMatch = text.match(/one\s+or\s+more\s*(?::|=)?\s*([^\n]+)/i);
    if (oneOrMoreMatch) {
      cooking.oneOrMore = oneOrMoreMatch[1]
        .split(/[,;]/)
        .map(s => s.trim())
        .filter(s => s.length > 0);
    }
    
    return cooking;
  }
  
  extractCraftingRecipe(text) {
    const crafting = {
      activate: null,
      target: null,
      action: null,
      materials: [],
      improveWith: []
    };
    
    // Extract activate/target pattern
    const activateMatch = text.match(/activate\s+(?:a\s+)?([^,\n]+?)(?:\s+on|\s+and)/i);
    if (activateMatch) {
      crafting.activate = activateMatch[1].trim();
    }
    
    const targetMatch = text.match(/(?:on|target)\s+(?:a\s+)?([^,\n]+?)(?:\s+to|\s+and)/i);
    if (targetMatch) {
      crafting.target = targetMatch[1].trim();
    }
    
    // Extract action (create, continue, improve)
    if (text.toLowerCase().includes("create")) crafting.action = "create";
    else if (text.toLowerCase().includes("continue")) crafting.action = "continue";
    else if (text.toLowerCase().includes("improve")) crafting.action = "improve";
    
    // Extract materials from tables or lists
    const materialPattern = /(\d+(?:\.\d+)?)\s*(?:kg|unit)?\s*(?:of\s+)?([a-z\s]+?)(?:\s*\n|\s*\||$)/gi;
    let match;
    while ((match = materialPattern.exec(text)) !== null) {
      const material = match[2].trim();
      if (material && material.length > 1) {
        crafting.materials.push({
          quantity: parseFloat(match[1]),
          material: material
        });
      }
    }
    
    return crafting;
  }
  
  calculateConfidence(recipe) {
    let score = 0;
    const maxScore = 10;
    
    // Has skills
    if (recipe.extracted.skills.length > 0) score += 2;
    
    // Has ingredients
    if (recipe.extracted.ingredients.length > 0) score += 2;
    if (recipe.extracted.ingredients.length > 3) score += 1;
    
    // Has tools
    if (recipe.extracted.tools.length > 0) score += 1;
    
    // Has containers
    if (recipe.extracted.containers.length > 0) score += 1;
    
    // Has cooking data
    if (recipe.cooking && (recipe.cooking.mandatory.length > 0 || recipe.cooking.container)) {
      score += 2;
    }
    
    // Has crafting data
    if (recipe.crafting && (recipe.crafting.activate || recipe.crafting.materials.length > 0)) {
      score += 2;
    }
    
    // Categories suggest recipe
    const recipeCats = recipe.categories.filter(c => 
      this.recipeCategories.some(rc => c.toLowerCase().includes(rc.toLowerCase()))
    );
    if (recipeCats.length > 0) score += 1;
    
    return score / maxScore;
  }
}

